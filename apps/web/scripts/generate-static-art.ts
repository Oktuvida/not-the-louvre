import { mkdir, readdir, rm, writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';
import process from 'node:process';
import {
	createMuseumWallPatternUrl,
	createMuseumWindowFrameUrl,
	createStickerBackgroundUrl
} from '../src/lib/features/home-entry-scene/canvas/museum-canvas';
import { getStickerControlPreset } from '../src/lib/features/shared-ui/sticker-controls';
import {
	MUSEUM_WALL_ASSET_NAME,
	MUSEUM_WINDOW_FRAME_ASSET_NAME,
	STICKER_CONTROL_SIZES,
	STICKER_VARIANTS,
	stickerBackgroundAssetName
} from '../src/lib/features/shared-ui/generated-art';
import { generatedArtDigest } from '../src/lib/server/deploy/generated-art-digest';

/*
 * Writes the generated museum artwork to `static/generated/` so the SSR HTML
 * can reference it by URL instead of carrying ~110-190KB of inline
 * `data:image/svg+xml` per document. The builders are pure string builders, so
 * this is deterministic: running it twice produces byte-identical files.
 *
 * The output is committed (dev and the vitest browser project serve `static/`
 * directly) and regenerated as the first step of `bun run build`, so a change
 * to the builders can never ship a stale texture. The version segment in each
 * filename is a digest of the artwork, written to
 * `shared-ui/generated-art-version.ts` alongside the files: that is what earns
 * the year-long `immutable` header in `apps/web/_headers`, because new bytes
 * can only arrive under a new name.
 */

const SVG_DATA_URL_PREFIX = 'data:image/svg+xml,';

const decodeSvgDataUrl = (dataUrl: string) => {
	if (!dataUrl.startsWith(SVG_DATA_URL_PREFIX)) {
		throw new Error(`expected an svg data url, received: ${dataUrl.slice(0, 32)}…`);
	}

	return decodeURIComponent(dataUrl.slice(SVG_DATA_URL_PREFIX.length));
};

const projectRoot = process.cwd();
const outputDirectory = resolve(projectRoot, 'static/generated');
const versionModulePath = resolve(
	projectRoot,
	'src/lib/features/shared-ui/generated-art-version.ts'
);

const assets: Array<{ name: string; markup: string }> = [
	{
		name: MUSEUM_WALL_ASSET_NAME,
		markup: decodeSvgDataUrl(createMuseumWallPatternUrl())
	},
	{
		name: MUSEUM_WINDOW_FRAME_ASSET_NAME,
		markup: decodeSvgDataUrl(createMuseumWindowFrameUrl())
	}
];

for (const size of STICKER_CONTROL_SIZES) {
	const preset = getStickerControlPreset(size);

	for (const variant of STICKER_VARIANTS) {
		assets.push({
			name: stickerBackgroundAssetName(size, variant),
			markup: decodeSvgDataUrl(
				createStickerBackgroundUrl(preset.minWidth, preset.height, { variant })
			)
		});
	}
}

// Derived here rather than read from the module below: the names these files
// are written under have to describe the bytes being written, not the bytes of
// the previous run.
const version = generatedArtDigest(assets);

// Recreated rather than merged so a superseded version cannot leave its files
// behind in the Workers asset bundle.
await rm(outputDirectory, { force: true, recursive: true });
await mkdir(outputDirectory, { recursive: true });

await Promise.all(
	assets.map((asset) =>
		writeFile(resolve(outputDirectory, `${asset.name}.${version}.svg`), asset.markup, 'utf8')
	)
);

await writeFile(
	versionModulePath,
	[
		'// Generated by scripts/generate-static-art.ts — do not edit by hand.',
		'//',
		'// A digest of every SVG the museum builders produce. It is the version',
		'// segment of each /generated/* filename, which is what makes the immutable',
		'// cache header on those files true: change a builder and the URLs change,',
		'// so nobody is served the previous artwork from a cache.',
		`export const GENERATED_ART_VERSION = '${version}';`,
		''
	].join('\n'),
	'utf8'
);

const written = (await readdir(outputDirectory)).length;

process.stdout.write(
	`Generated ${written} static art files at version ${version} in ${outputDirectory}\n`
);
