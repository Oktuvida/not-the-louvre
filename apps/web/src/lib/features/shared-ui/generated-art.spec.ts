import { readFileSync } from 'node:fs';
import { resolve } from 'node:path';
import process from 'node:process';
import { describe, expect, it } from 'vitest';
import {
	createMuseumWallPatternUrl,
	createMuseumWindowFrameUrl,
	createStickerBackgroundUrl
} from '../home-entry-scene/canvas/museum-canvas';
import { generatedArtDigest } from '#lib/server/deploy/generated-art-digest.js';
import {
	GENERATED_ART_VERSION,
	MUSEUM_WALL_ASSET_NAME,
	MUSEUM_WINDOW_FRAME_ASSET_NAME,
	STICKER_CONTROL_SIZES,
	STICKER_VARIANTS,
	museumWallPatternAssetUrl,
	museumWindowFrameAssetUrl,
	stickerBackgroundAssetName,
	stickerBackgroundAssetUrl
} from './generated-art';
import { getStickerControlPreset } from './sticker-controls';

/*
 * The generated art is committed under static/ and regenerated by
 * `scripts/generate-static-art.ts` at the start of every build. This locks the
 * three together — the builders, the committed files, and the version segment
 * in their URLs — so that touching a builder without re-running the generator
 * fails here rather than shipping new bytes under a filename that the
 * year-long `immutable` header promises can never change.
 */

const SVG_DATA_URL_PREFIX = 'data:image/svg+xml,';

const decodeSvgDataUrl = (dataUrl: string) =>
	decodeURIComponent(dataUrl.slice(SVG_DATA_URL_PREFIX.length));

const readGeneratedAsset = (assetUrl: string) =>
	readFileSync(resolve(process.cwd(), `static${assetUrl}`), 'utf8');

describe('generated static art', () => {
	it('serves the museum wall and window frame from versioned static files', () => {
		expect(museumWallPatternAssetUrl).toMatch(/^\/generated\/museum-wall\.[0-9a-f]{12}\.svg$/);
		expect(museumWindowFrameAssetUrl).toMatch(
			/^\/generated\/museum-window-frame\.[0-9a-f]{12}\.svg$/
		);

		expect(readGeneratedAsset(museumWallPatternAssetUrl)).toBe(
			decodeSvgDataUrl(createMuseumWallPatternUrl())
		);
		expect(readGeneratedAsset(museumWindowFrameAssetUrl)).toBe(
			decodeSvgDataUrl(createMuseumWindowFrameUrl())
		);
	});

	it('has a committed sticker background for every size and variant', () => {
		for (const size of STICKER_CONTROL_SIZES) {
			const preset = getStickerControlPreset(size);

			for (const variant of STICKER_VARIANTS) {
				const expected = decodeSvgDataUrl(
					createStickerBackgroundUrl(preset.minWidth, preset.height, { variant })
				);

				expect(readGeneratedAsset(stickerBackgroundAssetUrl(size, variant))).toBe(expected);
			}
		}
	});

	it('names the files after the artwork they hold, so `immutable` is true', () => {
		const sources = [
			{ markup: decodeSvgDataUrl(createMuseumWallPatternUrl()), name: MUSEUM_WALL_ASSET_NAME },
			{
				markup: decodeSvgDataUrl(createMuseumWindowFrameUrl()),
				name: MUSEUM_WINDOW_FRAME_ASSET_NAME
			},
			...STICKER_CONTROL_SIZES.flatMap((size) => {
				const preset = getStickerControlPreset(size);

				return STICKER_VARIANTS.map((variant) => ({
					markup: decodeSvgDataUrl(
						createStickerBackgroundUrl(preset.minWidth, preset.height, { variant })
					),
					name: stickerBackgroundAssetName(size, variant)
				}));
			})
		];

		// `/generated/*` is served `immutable, max-age=1y` and every build
		// rewrites these files from the builders. The only thing that keeps a
		// returning visitor off last week's artwork is this: new bytes, new name.
		expect(GENERATED_ART_VERSION).toBe(generatedArtDigest(sources));
	});
});
